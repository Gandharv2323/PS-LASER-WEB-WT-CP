// Generates services/db/seed.sql from the website's single source of truth
// (src/lib/pslaser/data.ts). Run: npx tsx services/db/generate-seed.ts <admin-bcrypt-hash>
import { writeFileSync } from "node:fs";
import { machines, services } from "../../src/lib/pslaser/data";

const q = (s: string) => `'${s.replace(/\\/g, "\\\\").replace(/'/g, "''")}'`;
const hash = process.argv[2];
if (!hash) throw new Error("pass the admin bcrypt hash as the first argument");

const lines: string[] = ["-- Generated by generate-seed.ts. Do not edit by hand.", "SET NAMES utf8mb4;", "USE pslaser;", ""];

lines.push("INSERT INTO users (name, email, password, role) VALUES");
lines.push(`  ('PS Laser Admin', 'admin@pslaser.local', ${q(hash)}, 'admin');`, "");

lines.push("INSERT INTO machines (slug, name, short_name, category, specs, image, sort_order) VALUES");
lines.push(
  machines
    .map((m, i) => `  (${q(m.slug)}, ${q(m.name)}, ${q(m.shortName)}, ${q(m.category)}, ${q(m.specs.join("\n"))}, ${q(m.image)}, ${i + 1})`)
    .join(",\n") + ";",
  "",
);

lines.push("INSERT INTO services (slug, title, description, image, sort_order) VALUES");
lines.push(
  services.map((s, i) => `  (${q(s.slug)}, ${q(s.title)}, ${q(s.text)}, ${q(s.image)}, ${i + 1})`).join(",\n") + ";",
  "",
);

// Max thickness from the company profile; densities are standard physical values.
lines.push(
  "INSERT INTO materials (code, name, max_thickness_mm, density_g_cm3) VALUES",
  "  ('MS', 'Mild Steel', 16, 7.85),",
  "  ('SS', 'Stainless Steel', 12, 8.00),",
  "  ('AL', 'Aluminium', 8, 2.70),",
  "  ('BR', 'Brass', 4, 8.50),",
  "  ('CU', 'Copper', 4, 8.96);",
  "",
  "-- SAMPLE rate card (is_sample = 1). Placeholder numbers for development; PS Laser sets real prices in the Laravel admin.",
  "INSERT INTO rates (material_code, thickness_from_mm, thickness_to_mm, cut_rate_per_m, pierce_rate, material_rate_per_kg) VALUES",
  "  ('MS', 0.5, 3, 10, 1, 75), ('MS', 3.01, 8, 22, 2, 72), ('MS', 8.01, 16, 45, 4, 70),",
  "  ('SS', 0.5, 3, 18, 1.5, 260), ('SS', 3.01, 12, 48, 4, 255),",
  "  ('AL', 0.5, 3, 16, 1.5, 290), ('AL', 3.01, 8, 38, 3, 285),",
  "  ('BR', 0.5, 4, 40, 3, 650), ('CU', 0.5, 4, 48, 3, 900);",
  "",
  "INSERT INTO settings (`key`, `value`) VALUES",
  "  ('bend_rate_inr', '8'), ('powder_coat_rate_per_sqm', '120'), ('gst_percent', '18'), ('rates_are_sample', '1');",
  "",
  "-- Demo work orders so the tracking pages have something to show (clearly fake customers).",
  "INSERT INTO work_orders (order_no, customer_name, customer_phone, description, machine_slug, quantity, status, due_date) VALUES",
  "  ('PSL-DEMO-001', 'Demo Customer A', '9000000001', 'MS 2 mm panel brackets, bent + powder coated', 'hsg-3kw-fiber-laser', 120, 'bending', DATE_ADD(CURDATE(), INTERVAL 5 DAY)),",
  "  ('PSL-DEMO-002', 'Demo Customer B', '9000000002', 'SS 1.5 mm perforated grill (turret punched)', 'amada-vela-ii-32t-turret-punch', 40, 'inspection', DATE_ADD(CURDATE(), INTERVAL 2 DAY));",
  "INSERT INTO work_order_events (work_order_id, status, note) VALUES",
  "  (1, 'received', 'Drawing received on WhatsApp'), (1, 'cutting', 'Cut on 3 kW fiber laser'), (1, 'bending', 'On 175 T press brake'),",
  "  (2, 'received', 'DXF approved'), (2, 'cutting', 'Punched on Amada 32 T'), (2, 'inspection', 'Dimensional check');",
);

writeFileSync(new URL("./seed.sql", import.meta.url), lines.join("\n") + "\n");
console.log("seed.sql written");
