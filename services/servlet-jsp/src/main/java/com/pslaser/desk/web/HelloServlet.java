package com.pslaser.desk.web;

import java.io.IOException;
import java.io.PrintWriter;
import java.text.SimpleDateFormat;
import java.util.Collections;
import java.util.Date;
import java.util.Map;
import javax.servlet.ServletException;
import javax.servlet.http.HttpServlet;
import javax.servlet.http.HttpServletRequest;
import javax.servlet.http.HttpServletResponse;

/**
 * "HELLO WORLD" SERVLET + SERVLETS GENERATING DYNAMIC CONTENT.
 *
 * Mapped in web.xml (servlet + servlet-mapping, url-pattern /hello) - the classic
 * deployment-descriptor way, as opposed to the @WebServlet annotations used elsewhere.
 *
 * Servlet architecture in one picture:
 *   browser --HTTP--> Tomcat Connector (port 8080) --> Engine/Host --> Context (/pslaser)
 *     --> filter chain (EncodingFilter, RequestLogFilter) --> this servlet's service()
 *     --> doGet(request, response) --> HTML written to response.getWriter() --> browser
 * Tomcat creates ONE instance of this class and calls doGet on many threads at once.
 *
 * Try: /pslaser/hello  and  /pslaser/hello?name=Shinde&lang=mr
 */
public class HelloServlet extends HttpServlet {
    private static final long serialVersionUID = 1L;

    @Override
    protected void doGet(HttpServletRequest req, HttpServletResponse resp) throws ServletException, IOException {
        resp.setContentType("text/html;charset=UTF-8");
        String name = req.getParameter("name");
        String lang = req.getParameter("lang");
        String greeting = "mr".equals(lang) ? "Namaskar" : "hi".equals(lang) ? "Namaste" : "Hello";
        String who = name == null || name.trim().isEmpty() ? "World" : name.trim();

        PrintWriter out = resp.getWriter();
        out.println("<!DOCTYPE html><html lang=\"en\"><head><meta charset=\"UTF-8\">");
        out.println("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">");
        out.println("<title>Hello World servlet - PS Laser</title>");
        out.println("<link rel=\"stylesheet\" href=\"https://cdn.jsdelivr.net/npm/bootstrap@4.6.2/dist/css/bootstrap.min.css\">");
        out.println("<link rel=\"stylesheet\" href=\"" + req.getContextPath() + "/css/app.css\"></head><body>");
        out.println("<div class=\"container py-4\">");
        out.println("<a href=\"" + req.getContextPath() + "/\"><img src=\"" + req.getContextPath()
                + "/img/ps-laser-logo.png\" alt=\"PS Laser\" height=\"48\"></a>");
        out.println("<h1 class=\"mt-3\">" + esc(greeting) + ", " + esc(who) + "!</h1>");
        out.println("<p class=\"lead\">This page was generated by <code>HelloServlet.doGet()</code> at "
                + new SimpleDateFormat("dd MMM yyyy, HH:mm:ss").format(new Date()) + " - reload and the time changes (dynamic content).</p>");

        out.println("<h2 class=\"h5 mt-4\">Request information</h2><div class=\"table-responsive\"><table class=\"table table-sm table-bordered bg-white\">");
        row(out, "Method", req.getMethod());
        row(out, "Request URI", req.getRequestURI());
        row(out, "Context path", req.getContextPath());
        row(out, "Servlet path", req.getServletPath());
        row(out, "Query string", req.getQueryString());
        row(out, "Protocol", req.getProtocol());
        row(out, "Scheme / server", req.getScheme() + "://" + req.getServerName() + ":" + req.getServerPort());
        row(out, "Remote address", req.getRemoteAddr());
        row(out, "Locale", String.valueOf(req.getLocale()));
        row(out, "Servlet name", getServletName());
        row(out, "Container", getServletContext().getServerInfo());
        row(out, "Thread", Thread.currentThread().getName());
        out.println("</table></div>");

        out.println("<h2 class=\"h5 mt-4\">Headers</h2><div class=\"table-responsive\"><table class=\"table table-sm table-bordered bg-white\">");
        for (String h : Collections.list(req.getHeaderNames())) row(out, h, req.getHeader(h));
        out.println("</table></div>");

        out.println("<h2 class=\"h5 mt-4\">Parameters</h2>");
        Map<String, String[]> params = req.getParameterMap();
        if (params.isEmpty()) {
            out.println("<p class=\"text-muted\">None. Try <a href=\"?name=Shinde&amp;lang=mr\">?name=Shinde&amp;lang=mr</a>.</p>");
        } else {
            out.println("<ul>");
            for (Map.Entry<String, String[]> e : params.entrySet())
                out.println("<li><code>" + esc(e.getKey()) + "</code> = " + esc(String.join(", ", e.getValue())) + "</li>");
            out.println("</ul>");
        }
        out.println("<p><a class=\"btn btn-ps\" href=\"" + req.getContextPath() + "/\">Back to Order Desk</a></p>");
        out.println("</div></body></html>");
    }

    private static void row(PrintWriter out, String k, String v) {
        out.println("<tr><th class=\"w-25\">" + esc(k) + "</th><td class=\"text-break\">" + esc(v == null ? "-" : v) + "</td></tr>");
    }

    /** Minimal HTML escaping - never echo request data raw (XSS). */
    static String esc(String s) {
        if (s == null) return "";
        StringBuilder b = new StringBuilder(s.length());
        for (char c : s.toCharArray()) {
            switch (c) {
                case '<': b.append("&lt;"); break;
                case '>': b.append("&gt;"); break;
                case '&': b.append("&amp;"); break;
                case '"': b.append("&quot;"); break;
                case '\'': b.append("&#39;"); break;
                default: b.append(c);
            }
        }
        return b.toString();
    }
}
